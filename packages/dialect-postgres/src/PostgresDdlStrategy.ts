import { SqlHelper } from '@ts-linq/core';
import type { ColumnMetadata, EntityMetadata } from '@ts-linq/types';
type LoggerLike = { warn(message: string, error?: unknown): void };
import { PgIndexBuilder } from './builders/PgIndexBuilder';
import { quoteIdentifier, quoteStringLiteral } from './quoting';

export class PostgresDdlStrategy {
  private readonly indexBuilder: PgIndexBuilder;

  constructor(private readonly logger?: LoggerLike) {
    this.indexBuilder = new PgIndexBuilder(logger);
  }
  public generateCreateTableSql(entityMetadata: EntityMetadata): string {
    const columnSqls = entityMetadata.columns.map((column: ColumnMetadata) => {
      if (column.isComputed && column.computedExpression) {
        // PostgreSQL supports only STORED
        const storage = column.computedStorage;
        if (storage && storage !== 'STORED') {
          this.logger?.warn(
            `Postgres: computedStorage='${storage}' is not supported; coercing to STORED for ${column.columnName}`
          );
        }
        return `${quoteIdentifier(column.columnName)} ${this.mapTypeToPg(column.type)} GENERATED ALWAYS AS (${column.computedExpression}) STORED`;
      }
      const mappedType = this.mapTypeToPg(column.type);
      const notNullSql = column.nullable ? '' : ' NOT NULL';

      let defaultSql = '';
      if (column.defaultExpression) {
        defaultSql = ` DEFAULT ${column.defaultExpression}`;
      } else if (column.defaultValue !== undefined) {
        defaultSql = ` DEFAULT ${SqlHelper.formatValue(column.defaultValue)}`;
      }

      // Auto-generated columns (identity / serial). Prefer identity syntax over SERIAL.
      // Only apply when caller didn't specify an explicit default.
      if (column.isGenerated && !defaultSql) {
        if (mappedType === 'INTEGER') {
          return `${quoteIdentifier(column.columnName)} INTEGER GENERATED BY DEFAULT AS IDENTITY${notNullSql}`;
        }
        this.logger?.warn(
          `Postgres: isGenerated is only supported for INTEGER identity columns; ignoring for ${column.columnName}`
        );
      }

      return `${quoteIdentifier(column.columnName)} ${mappedType}${notNullSql}${defaultSql}`;
    });
    if (entityMetadata.primaryKeys && entityMetadata.primaryKeys.length > 0) {
      const primaryKeySql = entityMetadata.primaryKeys
        .map((primaryKey) =>
          quoteIdentifier(
            entityMetadata.columns.find((column) => column.propertyName === primaryKey)
              ?.columnName || primaryKey
          )
        )
        .join(', ');
      columnSqls.push(`PRIMARY KEY (${primaryKeySql})`);
    }

    for (const cc of entityMetadata.checkConstraints ?? []) {
      columnSqls.push(`CONSTRAINT ${quoteIdentifier(cc.name)} CHECK (${cc.sql})`);
    }

    return `CREATE TABLE IF NOT EXISTS ${quoteIdentifier(entityMetadata.tableName)} (${columnSqls.join(', ')})`;
  }

  public generateCreateIndexSql(
    table: string,
    index: {
      name: string;
      columns: string[];
      unique: boolean;
      where?: string;
      orders?: { [column: string]: 'ASC' | 'DESC' };
      expressions?: string[];
      collations?: { [column: string]: string };
      nulls?: { [column: string]: 'FIRST' | 'LAST' };
      using?: 'btree' | 'hash' | 'gin' | 'gist';
      concurrently?: boolean;
      withParams?: Record<string, string | number | boolean>;
    }
  ): string {
    return this.indexBuilder.buildCreateIndexSql(table, index);
  }

  public generateAddColumnSql(
    tableName: string,
    column: Omit<ColumnMetadata, 'propertyName'>
  ): string {
    const mappedType = this.mapTypeToPg(column.type);
    const notNullSql = column.nullable ? '' : ' NOT NULL';
    let defaultSql = '';
    if (column.defaultExpression) {
      defaultSql = ` DEFAULT ${column.defaultExpression}`;
    } else if (column.defaultValue !== undefined) {
      defaultSql = ` DEFAULT ${SqlHelper.formatValue(column.defaultValue)}`;
    }
    return `ALTER TABLE ${quoteIdentifier(tableName)} ADD COLUMN ${quoteIdentifier(column.columnName)} ${mappedType}${notNullSql}${defaultSql}`;
  }

  public generateDropColumnSql(tableName: string, columnName: string): string {
    return `ALTER TABLE ${quoteIdentifier(tableName)} DROP COLUMN ${quoteIdentifier(columnName)}`;
  }

  public generateAlterColumnTypeSql(
    tableName: string,
    columnName: string,
    newType: string
  ): string {
    const mappedType = this.mapTypeToPg(newType);
    return `ALTER TABLE ${quoteIdentifier(tableName)} ALTER COLUMN ${quoteIdentifier(columnName)} TYPE ${mappedType}`;
  }

  public generateRenameTableSql(tableName: string, newTableName: string): string {
    return `ALTER TABLE ${quoteIdentifier(tableName)} RENAME TO ${quoteIdentifier(newTableName)}`;
  }

  public generateForeignKeySql(
    tableName: string,
    fk: {
      name: string;
      columnName: string;
      relatedTableName: string;
      relatedColumnName: string;
      onDelete?: string;
      onUpdate?: string;
    }
  ): string {
    let sql = `ALTER TABLE ${quoteIdentifier(tableName)} ADD CONSTRAINT ${quoteIdentifier(fk.name)} FOREIGN KEY (${quoteIdentifier(fk.columnName)}) REFERENCES ${quoteIdentifier(fk.relatedTableName)} (${quoteIdentifier(fk.relatedColumnName)})`;
    if (fk.onDelete && fk.onDelete !== 'NO ACTION') {
      sql += ` ON DELETE ${fk.onDelete}`;
    }
    if (fk.onUpdate && fk.onUpdate !== 'NO ACTION') {
      sql += ` ON UPDATE ${fk.onUpdate}`;
    }
    return sql;
  }

  /**
   * Generates `ALTER TABLE ... ADD CONSTRAINT ... UNIQUE (...)` for an alternate key.
   * Mirrors EF Core's HasAlternateKey DDL for PostgreSQL.
   */
  public generateAddUniqueConstraintSql(
    tableName: string,
    name: string,
    columns: string[]
  ): string {
    const cols = columns.map((c) => quoteIdentifier(c)).join(', ');
    return `ALTER TABLE ${quoteIdentifier(tableName)} ADD CONSTRAINT ${quoteIdentifier(name)} UNIQUE (${cols})`;
  }

  /**
   * Generates `ALTER TABLE ... DROP CONSTRAINT ...` for an alternate key.
   */
  public generateDropUniqueConstraintSql(tableName: string, name: string): string {
    return `ALTER TABLE ${quoteIdentifier(tableName)} DROP CONSTRAINT IF EXISTS ${quoteIdentifier(name)}`;
  }

  // index helpers relocated to PgIndexBuilder

  /**
   * Generates COMMENT ON TABLE / COLUMN statements for the entity and its columns.
   * Returns an empty array when neither the table nor any column has a comment.
   */
  public generateCommentSql(entityMetadata: EntityMetadata): string[] {
    const stmts: string[] = [];
    const table = entityMetadata.tableName;
    if (entityMetadata.comment) {
      stmts.push(
        `COMMENT ON TABLE ${quoteIdentifier(table)} IS ${quoteStringLiteral(entityMetadata.comment)}`
      );
    }
    for (const col of entityMetadata.columns) {
      if (col.comment) {
        stmts.push(
          `COMMENT ON COLUMN ${quoteIdentifier(table)}.${quoteIdentifier(col.columnName)} IS ${quoteStringLiteral(col.comment)}`
        );
      }
    }
    return stmts;
  }

  public mapTypeToPg(type: string): string {
    const key = (type || '').toUpperCase();
    const map: Record<string, string> = {
      TEXT: 'TEXT',
      STRING: 'TEXT',
      INTEGER: 'INTEGER',
      NUMBER: 'INTEGER',
      REAL: 'DOUBLE PRECISION',
      FLOAT: 'DOUBLE PRECISION',
      DOUBLE: 'DOUBLE PRECISION',
      BOOLEAN: 'BOOLEAN',
      DATETIME: 'TIMESTAMPTZ',
      DATE: 'TIMESTAMPTZ',
      BLOB: 'BYTEA',
      UUID: 'UUID',
      JSONB: 'JSONB',
      JSON: 'JSON'
    };
    return map[key] ?? 'TEXT';
  }
}
